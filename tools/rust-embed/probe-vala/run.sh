#!/usr/bin/env bash
# run.sh — build the Vala probe, sweep all 206 scramble types through
# JavaScriptCore, and check the dump against the value every other engine
# produces (RUST-PORT.md §7: md5 7750f9e8… over the 206-line dump block).
#
# Three runs, each a mode of the same binary:
#   1. the dump sweep                       (byte-diffed against the reference)
#   2. the dump sweep on a worker thread    (rule 4: off the UI thread)
#   3. the host-driven API                  (setSeed/getScramble/getImage as
#      Vala→JS calls, counted against the reference's 206/177)
#
#   ./run.sh              build + all three (~35 s) + verdict
#   DIFF=1 ./run.sh       also diff run 1 against a fresh node reference
#
# Needs valac and `javascriptcoregtk-6.0` (webkitgtk-6.0's engine) installed.
set -uo pipefail
cd "$(dirname "$0")"

REPO="$(cd ../../.. && pwd)"
BUNDLE="$REPO/node_modules/cstimer_module/cstimer_module.js"
TYPES="../types.json"                       # generated by gen-types.mjs
EXPECTED_MD5=7750f9e8e1eaf18540c43a8ec7f6d574
OUT="$(mktemp -d)"
trap 'rm -rf "$OUT"' EXIT

if ! command -v valac >/dev/null; then
  echo "valac not found — install vala" >&2; exit 1
fi
if ! pkg-config --exists javascriptcoregtk-6.0; then
  echo "javascriptcoregtk-6.0 not found — install webkitgtk-6.0" >&2; exit 1
fi

# Binaries and object files land in the gitignored cargo target dir.
BUILD="../target/vala"
mkdir -p "$BUILD"

printf '=== build ===\n'
if ! valac -o "$BUILD/probe-vala" --pkg javascriptcoregtk-6.0 main.vala >"$OUT/build.txt" 2>&1; then
  cat "$OUT/build.txt"; exit 1
fi
grep -v '^$' "$OUT/build.txt" || true

printf '\n=== sweep ===\n'
if ! "$BUILD/probe-vala" "$BUNDLE" "$TYPES" . >"$OUT/out.txt" 2>&1; then
  cat "$OUT/out.txt"; exit 1
fi

# Same extraction as ../run.sh: the dump block only — counts and timings
# legitimately differ per engine.
awk '/^===DUMP===/{p=1;next} /^===COUNTS===/{p=0} p' "$OUT/out.txt" >"$OUT/dump.txt"
MD5="$(md5sum <"$OUT/dump.txt" | cut -c1-32)"
LINES="$(wc -l <"$OUT/dump.txt")"
grep -E '^(generated OK|\[vala/jsc\])' "$OUT/out.txt" | sed 's/^/  /'

# Rule 4: a 4x4 WCA scramble must never run on the UI thread. Same sweep with
# the context created and used on a worker thread, no GLib main loop.
printf '\n=== sweep (worker thread, no main loop) ===\n'
if ! "$BUILD/probe-vala" --thread "$BUNDLE" "$TYPES" . >"$OUT/out-thread.txt" 2>&1; then
  cat "$OUT/out-thread.txt"; exit 1
fi
awk '/^===DUMP===/{p=1;next} /^===COUNTS===/{p=0} p' "$OUT/out-thread.txt" >"$OUT/dump-thread.txt"
THREAD_MD5="$(md5sum <"$OUT/dump-thread.txt" | cut -c1-32)"
grep -E '^(generated OK|\[vala/jsc\])' "$OUT/out-thread.txt" | sed 's/^/  /'

# The host→module path: three functions called from Vala, typed arguments in,
# string | false | exception out. Counts compared against the reference run.
printf '\n=== host-driven API (Vala -> JS) ===\n'
if ! "$BUILD/probe-vala" --api "$BUNDLE" "$TYPES" . >"$OUT/out-api.txt" 2>&1; then
  cat "$OUT/out-api.txt"; exit 1
fi
grep -E '^\[vala/(jsc|api)\]' "$OUT/out-api.txt" | sed 's/^/  /'
API_LINE="$(grep -o 'host-driven.*' "$OUT/out-api.txt")"

printf '\n=== verdict ===\n'
printf '  vala/jsc    %s lines  %s\n' "$LINES" "$MD5"

pass=0
if [[ "$MD5" == "$EXPECTED_MD5" ]]; then
  printf '  IDENTICAL (all 206 types byte-for-byte, %s)\n' "${EXPECTED_MD5:0:12}"
  pass=1
else
  printf '  DIFFERS from the reference hash %s\n' "$EXPECTED_MD5"
fi
if [[ "$THREAD_MD5" == "$EXPECTED_MD5" ]]; then
  printf '  worker thread IDENTICAL   %s\n' "$THREAD_MD5"
else
  printf '  worker thread DIFFERS     %s\n' "$THREAD_MD5"
  pass=0
fi
printf '  host API    %s\n' "$API_LINE"

if [[ -n "${DIFF:-}" ]]; then
  node ../node-reference.cjs >"$OUT/node.txt" 2>&1 || { cat "$OUT/node.txt"; exit 1; }
  awk '/^===DUMP===/{p=1;next} /^===COUNTS===/{p=0} p' "$OUT/node.txt" >"$OUT/node.dump"
  if diff -q "$OUT/node.dump" "$OUT/dump.txt" >/dev/null; then
    printf '  vs fresh node reference: IDENTICAL\n'
  else
    printf '  vs fresh node reference: DIFFERS\n'
    diff "$OUT/node.dump" "$OUT/dump.txt" | head -8
    pass=0
  fi
fi

[[ "$pass" -eq 1 ]] || exit 1
