//! Shared plumbing for the cstimer_module engine probes.
//!
//! The probes answer one question: *can a Rust project run the
//! `cstimer_module` bundle inside a JS engine instead of porting it?* Each
//! engine probe evaluates the real bundle, drives the app's own 206-type
//! catalogue, and prints an `id<TAB>json-string` dump. `run.sh` diffs those
//! dumps against `node-reference.cjs` — byte-identical output is the pass bar.
//!
//! See RUST-PORT.md for the findings these probes produced.

use std::path::{Path, PathBuf};

/// Walk up from this crate until we find the app repo root (marked by a
/// `package.json` next to `node_modules/cstimer_module`).
pub fn repo_root() -> PathBuf {
    let mut dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    loop {
        if dir.join("package.json").is_file()
            && dir.join("node_modules/cstimer_module/cstimer_module.js").is_file()
        {
            return dir;
        }
        if !dir.pop() {
            panic!(
                "could not find the cstimer-gtk repo root above {}",
                env!("CARGO_MANIFEST_DIR")
            );
        }
    }
}

/// The Closure-compiled bundle under test.
pub fn bundle_path() -> PathBuf {
    repo_root().join("node_modules/cstimer_module/cstimer_module.js")
}

/// `id` + `defaultLength` for all 206 types, generated by `gen-types.mjs`
/// from `src/core/scrambleTypes.ts`, so probes exercise the app's own
/// catalogue rather than the bundle's raw `getScrambleTypes()` ordering.
pub fn types_json() -> String {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../types.json");
    std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("reading {}: {e}", path.display()))
}

/// The host shim: everything the bundle expects from a Node-ish global.
///
/// The bundle's `isInNode` test (csTimer's `lib/utillib.js`) is
///     typeof process === 'object' && typeof require === 'function'
///     && typeof global === 'object'
/// and that flag flips `execBoth()` into the *worker* branch — the branch
/// that installs `module.exports`, `self.$` and `self.kernel`. Fake those
/// three globals and the bundle loads with no other host support.
///
/// Two extras are needed:
///   - `SCRAMBLE_NOOBST` / `SCRAMBLE_NOOBSS`: csTimer language strings the
///     module does not bundle. Without them `333noob` throws *and* desyncs
///     the shared seeded RNG, corrupting every later type in the dump.
///   - `String.prototype.substr`: guarded, because boa 0.22 omits this
///     Annex B method and exactly 3 types (`pyrm`, `mpyr`, `333noob`) call it.
pub const SHIM: &str = r#"
(function(){
  var g = globalThis;
  g.global = g;
  g.process = {};
  g.require = function(){ return {}; };
  g.module = { exports: {} };
  g.console = { log: function(){}, warn: function(){}, error: function(){} };

  g.SCRAMBLE_NOOBST = [
    ['turn the top face', 'turn the bottom face'],
    ['turn the right face', 'turn the left face'],
    ['turn the front face', 'turn the back face']
  ];
  g.SCRAMBLE_NOOBSS =
    ' clockwise by 90 degrees,| counterclockwise by 90 degrees,| by 180 degrees,';

  if (!String.prototype.substr) {
    String.prototype.substr = function(start, len) {
      var s = String(this);
      start = start < 0 ? Math.max(s.length + start, 0) : Math.min(start, s.length);
      if (len === undefined) return s.slice(start);
      return s.slice(start, start + Math.max(len, 0));
    };
  }
  return 'shim-ok';
})()
"#;

/// The JS every probe runs: seed once, then walk the catalogue in lockstep,
/// calling `getImage` between scrambles so the RNG stream stays aligned with
/// the Node reference (which does the same). Returns an expression that
/// evaluates to one string holding both the dump and the counts.
pub fn sweep_expr(types: &str) -> String {
    let types = types.replace('\\', "\\\\").replace('\'', "\\'");
    format!(
        r#"
      (function(){{
        var c = globalThis.module.exports;
        var types = JSON.parse('{types}');
        c.setSeed('42');
        var ok = 0, empty = 0, img = 0, failed = [], slow = [], dump = [];
        var tAll = Date.now();
        for (var i = 0; i < types.length; i++) {{
          var ty = types[i];
          var s0 = Date.now();
          var scr;
          try {{ scr = c.getScramble(ty.id, ty.len); }}
          catch (e) {{ failed.push(ty.id + ': scramble ERROR ' + e.message); continue; }}
          slow.push([Date.now() - s0, ty.id]);
          dump.push(ty.id + '\t' + JSON.stringify(String(scr)));
          if (String(scr).trim() === '') {{ empty++; }} else {{ ok++; }}
          try {{
            var im = c.getImage(scr, ty.id);
            if (typeof im === 'string' && im.length) img++;
          }} catch (e) {{ failed.push(ty.id + ': image ERROR ' + e.message); }}
        }}
        slow.sort(function(a, b) {{ return b[0] - a[0]; }});
        var out = [];
        out.push('generated OK=' + ok + ' empty=' + empty + ' images=' + img +
                 ' failures=' + failed.length + ' total=' + types.length);
        for (var i = 0; i < failed.length; i++) out.push('  FAIL ' + failed[i]);
        out.push('sweep wall time: ' + (Date.now() - tAll) + 'ms');
        out.push('slowest types:');
        for (var i = 0; i < Math.min(5, slow.length); i++) {{
          out.push('  ' + slow[i][1] + ' ' + slow[i][0] + 'ms');
        }}
        return '===DUMP===\n' + dump.join('\n') + '\n===COUNTS===\n' + out.join('\n');
      }})()
    "#,
        types = types
    )
}

/// `sweep_expr` with an `fs` hand-off appended, for engines whose bridge
/// cannot return a value from JS (edon/libnode: `eval_blocking` resolves `()`).
pub fn sweep_to_file_expr(types: &str, out_path: &str) -> String {
    let quoted = serde_json::to_string(out_path).expect("quote path");
    format!(
        r#"
      (function(){{
        var body = {sweep};
        require('fs').writeFileSync({out}, body, 'utf8');
        return 'written';
      }})()
    "#,
        sweep = sweep_expr(types),
        out = quoted
    )
}

/// Split a probe's stdout into (dump lines, counts block) around the markers.
pub fn split_output(text: &str) -> (Vec<String>, String) {
    let mut dump = Vec::new();
    let mut counts = String::new();
    let mut in_dump = false;
    let mut in_counts = false;
    for line in text.lines() {
        match line {
            "===DUMP===" => in_dump = true,
            "===COUNTS===" => {
                in_dump = false;
                in_counts = true;
            }
            _ if in_dump => dump.push(line.to_string()),
            _ if in_counts => {
                counts.push_str(line);
                counts.push('\n');
            }
            _ => {}
        }
    }
    (dump, counts)
}

/// Emit a probe report: engine banner lines first, then the marked dump and
/// counts blocks. `run.sh` extracts the dump between the markers, so every
/// probe must print them even though it parsed them away.
pub fn print_report(dump: &[String], counts: &str) {
    println!("===DUMP===");
    for line in dump {
        println!("{line}");
    }
    print!("===COUNTS===\n{counts}");
}
