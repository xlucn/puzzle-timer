/*
 * store.ts — persistence for sessions and their solves.
 *
 * Node-only (AGENTS.md rule 2): `fs`/`path`/`os` live here. Note that the XDG
 * data directory is read from the environment rather than via
 * `GLib.get_user_data_dir()` — rule 3 keeps every `gi:*` import inside src/ui/,
 * and the two agree: `XDG_DATA_HOME` when it is absolute (per the spec a
 * relative value is ignored), otherwise `~/.local/share`.
 *
 * Layout:
 *
 *   ~/.local/share/cstimer-gtk/prefs.json               app settings
 *   ~/.local/share/cstimer-gtk/sessions/_index.json     which sessions exist + which is active
 *   ~/.local/share/cstimer-gtk/sessions/default.json    one file of solves per session
 *
 * The index is the source of truth for names and the active session; each
 * session file keeps the original shape (`{version: 1, solves}`), so a
 * pre-index `default.json` *is* the migration — a missing index is rebuilt
 * from whatever session files are on disk, which is also the recovery path
 * when an index is corrupted or hand-edited. `_index.json` cannot be
 * mistaken for a session file: generated ids never start with `_`.
 *
 * Writes are atomic — the bytes go to `<file>.tmp` first and are renamed over
 * the target, so a crash mid-write can never truncate a session. They are
 * also debounced (a solve every few seconds does not deserve an fsync each
 * time): `scheduleSave()` serialises *now* and writes a moment later, `flush()`
 * writes whatever is still pending. Saves are tracked per file, so switching
 * sessions cannot make one session's queued write land in another's file. The
 * window's close handler and the process's exit hook both call `flush()`, so
 * a solve recorded a millisecond before quitting still survives.
 *
 * A file that cannot be parsed is moved aside (`*.corrupt-<timestamp>`) and
 * reported instead of being overwritten — losing a whole session silently
 * would be the worst possible failure for a timer.
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

import type { Solve } from '../core/session.js'
import { MAX_COMMENT_LENGTH } from '../core/session.js'
import { PREFERENCES_FILE_VERSION, type Preferences, normalizePreferences } from '../core/preferences.js'
import { MAX_NAME_LENGTH, type SessionEntry } from '../core/sessionLibrary.js'

/** Bumped only when a session file's shape changes incompatibly. */
export const SESSION_FILE_VERSION = 1
/** Bumped only when the index shape changes incompatibly. */
export const INDEX_FILE_VERSION = 1

const APP_DIR = 'cstimer-gtk'
const SESSION_SUBDIR = 'sessions'
const INDEX_FILE = '_index.json'
const PREFERENCES_FILE = 'prefs.json'
const DEFAULT_SESSION = 'default'

/** Coalesces the writes that arrive while a solve is being recorded. */
const SAVE_DELAY_MS = 250

/**
 * Ids are generated by src/core/sessionLibrary.ts, but they come back off disk
 * too (the rebuild path reads file names), so they are validated before they
 * are ever joined into a path: no separators, no dots, no case tricks.
 */
const ID_PATTERN = /^[a-z0-9][a-z0-9-]{0,63}$/
/** Exactly the shape `rebuild()` accepts as a session file name. */
const SESSION_FILE_PATTERN = /^([a-z0-9][a-z0-9-]{0,63})\.json$/

function dataHome(): string {
  const xdg = process.env.XDG_DATA_HOME
  if (xdg !== undefined && path.isAbsolute(xdg)) return xdg
  return path.join(os.homedir(), '.local', 'share')
}

function sessionsDir(): string {
  return path.join(dataHome(), APP_DIR, SESSION_SUBDIR)
}

/** Absolute path of the index that lists the sessions. */
export function indexPath(): string {
  return path.join(sessionsDir(), INDEX_FILE)
}

/** Absolute path of the preferences file (app-wide, next to `sessions/`). */
export function preferencesPath(): string {
  return path.join(dataHome(), APP_DIR, PREFERENCES_FILE)
}

/** Absolute path of one session's solve file. Throws on a malformed id. */
export function sessionFilePath(id: string): string {
  if (!ID_PATTERN.test(id)) throw new Error(`invalid session id: ${JSON.stringify(id)}`)
  return path.join(sessionsDir(), `${id}.json`)
}

export interface LoadResult {
  /** Solves read from disk — empty when there is no file (or it was unreadable). */
  solves: Solve[]
  /** Human-readable note when the file had to be moved aside or partly skipped. */
  notice: string | null
}

export interface IndexResult {
  /** The sessions on disk, possibly rebuilt from the session files. */
  sessions: SessionEntry[]
  /** The session to open first; null only when there are no session files at all. */
  activeId: string | null
  /** Human-readable note when the index had to be rebuilt or partly skipped. */
  notice: string | null
}

export interface PreferencesResult {
  /** Preferences from disk, field-validated; defaults when there is no file. */
  preferences: Preferences
  /** Human-readable note when the file had to be moved aside. */
  notice: string | null
}

function isSolve(value: unknown): value is Solve {
  if (typeof value !== 'object' || value === null) return false
  const solve = value as Record<string, unknown>
  const finite = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v)
  // Both fields are optional, so absent is always fine (files written before
  // they existed). A present one must be of the exact shape the rest of the
  // app assumes — an unrecognised penalty would silently become "OK" in the
  // statistics, and an unbounded comment could not be shown meaningfully, so
  // both reject the whole solve and it is skipped with a notice rather than
  // loaded wrong.
  const penaltyOk =
    solve.penalty === undefined || solve.penalty === 'plus2' || solve.penalty === 'dnf'
  const commentOk =
    solve.comment === undefined ||
    (typeof solve.comment === 'string' && solve.comment.length <= MAX_COMMENT_LENGTH)
  return (
    penaltyOk &&
    commentOk &&
    finite(solve.id) &&
    Number.isInteger(solve.id) &&
    solve.id >= 0 &&
    finite(solve.timeMs) &&
    solve.timeMs >= 0 &&
    typeof solve.scramble === 'string' &&
    typeof solve.scrambleType === 'string' &&
    finite(solve.createdAtMs)
  )
}

/** A session entry as it may legally appear in the index. */
function isEntry(value: unknown): value is SessionEntry {
  if (typeof value !== 'object' || value === null) return false
  const candidate = value as Record<string, unknown>
  return (
    typeof candidate.id === 'string' &&
    ID_PATTERN.test(candidate.id) &&
    typeof candidate.name === 'string' &&
    candidate.name.trim().length > 0 &&
    candidate.name.trim().length <= MAX_NAME_LENGTH
  )
}

/**
 * Rebuild the session list from the files themselves. This is both the
 * first-run path (no index yet — including M2's single `default.json`) and
 * the recovery path after an index was quarantined: solves are never lost
 * because a list of them broke. Names fall back to a humanised id, which is
 * the best a file name can offer.
 */
function rebuildFromFiles(): { sessions: SessionEntry[]; activeId: string | null } {
  let names: string[] = []
  try {
    names = fs.readdirSync(sessionsDir())
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
      console.error(`[store] could not list ${sessionsDir()}: ${messageOf(error)}`)
    }
    return { sessions: [], activeId: null }
  }

  const sessions: SessionEntry[] = names
    .map((name) => SESSION_FILE_PATTERN.exec(name)?.[1])
    .filter((id): id is string => id !== undefined)
    .sort()
    .map((id) => ({ id, name: humanName(id) }))

  const activeId = sessions.some((entry) => entry.id === DEFAULT_SESSION)
    ? DEFAULT_SESSION
    : (sessions[0]?.id ?? null)
  return { sessions, activeId }
}

/** 'meet-weekly' → 'Meet weekly' — what a recovered session is called. */
function humanName(id: string): string {
  const words = id.replace(/-/g, ' ')
  return words.charAt(0).toUpperCase() + words.slice(1)
}

/**
 * Read the index. A missing index means "start from the files" (fresh install
 * or the pre-index layout); anything else that cannot be understood is moved
 * aside and reported, then the files are used anyway — the notice tells the
 * app to say so, never to overwrite.
 */
export function loadIndex(): IndexResult {
  const file = indexPath()

  let raw: string
  try {
    raw = fs.readFileSync(file, 'utf8')
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
      return { ...rebuildFromFiles(), notice: null }
    }
    return { ...rebuildFromFiles(), notice: `${file} could not be read: ${messageOf(error)}` }
  }

  let parsed: unknown
  try {
    parsed = JSON.parse(raw)
  } catch {
    return { ...rebuildFromFiles(), notice: quarantine(file, 'not valid JSON') }
  }

  if (
    typeof parsed !== 'object' ||
    parsed === null ||
    !Array.isArray((parsed as { sessions?: unknown }).sessions) ||
    (parsed as { version?: unknown }).version !== INDEX_FILE_VERSION
  ) {
    return { ...rebuildFromFiles(), notice: quarantine(file, 'unrecognised format') }
  }

  const entries = (parsed as { sessions: unknown[] }).sessions
  const sessions: SessionEntry[] = []
  const seen = new Set<string>()
  let skipped = 0
  for (const entry of entries) {
    if (!isEntry(entry) || seen.has(entry.id)) {
      skipped += 1
      continue
    }
    seen.add(entry.id)
    const stored: SessionEntry = { id: entry.id, name: entry.name.trim() }
    // Optional, and shape-checked at load: the index is hand-editable, and
    // a non-string here must not reach the dropdowns.
    if (typeof entry.scrambleType === 'string' && entry.scrambleType.length > 0) {
      stored.scrambleType = entry.scrambleType
    }
    sessions.push(stored)
  }

  if (sessions.length === 0) {
    const rebuilt = rebuildFromFiles()
    return { ...rebuilt, notice: `${file} listed no usable sessions; rebuilt from the files on disk` }
  }

  const active = (parsed as { active?: unknown }).active
  const activeId =
    typeof active === 'string' && seen.has(active) ? active : sessions[0].id

  return {
    sessions,
    activeId,
    notice: skipped > 0 ? `${file}: skipped ${skipped} unreadable session(s)` : null,
  }
}

/**
 * Write the index now. Rare — only create / rename / delete / switch change
 * it — so there is nothing to debounce, and an immediate atomic write means a
 * crash right after deleting a session cannot leave a ghost entry behind.
 */
export function saveIndex(sessions: readonly SessionEntry[], activeId: string | null): void {
  const data = `${JSON.stringify(
    { version: INDEX_FILE_VERSION, active: activeId, sessions },
    null,
    2,
  )}\n`
  writeAtomically(indexPath(), data)
}

/**
 * Read the preferences. A missing file means "defaults" (fresh install);
 * anything else that cannot be understood is moved aside and reported, then
 * the defaults are used anyway — the notice tells the app to say so, never to
 * overwrite. Field-level validation happens in core (normalizePreferences).
 */
export function loadPreferences(): PreferencesResult {
  const file = preferencesPath()

  let raw: string
  try {
    raw = fs.readFileSync(file, 'utf8')
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
      return { preferences: normalizePreferences(undefined), notice: null }
    }
    return {
      preferences: normalizePreferences(undefined),
      notice: `${file} could not be read: ${messageOf(error)}`,
    }
  }

  let parsed: unknown
  try {
    parsed = JSON.parse(raw)
  } catch {
    return { preferences: normalizePreferences(undefined), notice: quarantine(file, 'not valid JSON') }
  }

  if (
    typeof parsed !== 'object' ||
    parsed === null ||
    (parsed as { version?: unknown }).version !== PREFERENCES_FILE_VERSION
  ) {
    return {
      preferences: normalizePreferences(undefined),
      notice: quarantine(file, 'unrecognised format'),
    }
  }

  return { preferences: normalizePreferences(parsed), notice: null }
}

/**
 * Write the preferences now. A few dozen bytes, changed only when the user
 * moves a setting — nothing to debounce, and an immediate atomic write means
 * a quit right after a change cannot lose it.
 */
export function savePreferences(preferences: Preferences): void {
  const data = `${JSON.stringify({ version: PREFERENCES_FILE_VERSION, ...preferences }, null, 2)}\n`
  writeAtomically(preferencesPath(), data)
}

/**
 * Read one session's solves. Missing file → no solves and no notice (a
 * session can exist without a file until its first solve); anything else that
 * cannot be understood is moved aside and reported.
 */
export function loadSession(id: string): LoadResult {
  const file = sessionFilePath(id)

  let raw: string
  try {
    raw = fs.readFileSync(file, 'utf8')
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return { solves: [], notice: null }
    return { solves: [], notice: `${file} could not be read: ${messageOf(error)}` }
  }

  let parsed: unknown
  try {
    parsed = JSON.parse(raw)
  } catch {
    return { solves: [], notice: quarantine(file, 'not valid JSON') }
  }

  if (
    typeof parsed !== 'object' ||
    parsed === null ||
    !Array.isArray((parsed as { solves?: unknown }).solves) ||
    (parsed as { version?: unknown }).version !== SESSION_FILE_VERSION
  ) {
    return { solves: [], notice: quarantine(file, 'unrecognised format') }
  }

  const entries = (parsed as { solves: unknown[] }).solves
  const solves: Solve[] = []
  let skipped = 0
  for (const entry of entries) {
    if (isSolve(entry)) solves.push(entry)
    else skipped += 1
  }

  return {
    solves,
    notice: skipped > 0 ? `${file}: skipped ${skipped} unreadable solve(s)` : null,
  }
}

/**
 * Serialise now, write in a moment — keyed by session id, so the queued bytes
 * belong to the session they were serialised from even if another one is
 * active by the time the timer fires. Serialising eagerly matters: the session
 * array keeps changing while the debounce clock runs, and the JSON that gets
 * written must describe the state the listener saw.
 */
export function scheduleSave(id: string, solves: readonly Solve[]): void {
  const data = `${JSON.stringify({ version: SESSION_FILE_VERSION, solves }, null, 2)}\n`
  pending.set(sessionFilePath(id), data)
  if (writeTimer !== null) return
  writeTimer = setTimeout(() => {
    writeTimer = null
    flush()
  }, SAVE_DELAY_MS)
  // Never keep the process (or the loop) alive just for a pending write.
  writeTimer.unref?.()
}

/** Write every pending change immediately. Safe to call when nothing is pending. */
export function flush(): void {
  if (writeTimer !== null) {
    clearTimeout(writeTimer)
    writeTimer = null
  }
  for (const [file, data] of [...pending]) {
    // A failed write keeps its entry: try again at the next save/flush
    // rather than dropping the solve that produced it.
    if (writeAtomically(file, data)) pending.delete(file)
  }
}

/** Forget any queued write for a session — used before its file goes away. */
export function dropPending(id: string): void {
  pending.delete(sessionFilePath(id))
}

/**
 * Delete a session's file. The queued write is dropped first: a save that was
 * scheduled a moment before the delete would otherwise resurrect the file and
 * leave an orphan the index no longer knows about.
 */
export function deleteSessionFile(id: string): void {
  const file = sessionFilePath(id)
  dropPending(id)
  try {
    fs.unlinkSync(file)
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
      console.error(`[store] could not remove ${file}: ${messageOf(error)}`)
    }
  }
}

/** File path → serialised JSON, one entry per session with an unsaved change. */
const pending = new Map<string, string>()
let writeTimer: NodeJS.Timeout | null = null

/** Atomic: bytes to `<file>.tmp`, then renamed over the target. */
function writeAtomically(file: string, data: string): boolean {
  const temp = `${file}.tmp`
  try {
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(temp, data, 'utf8')
    fs.renameSync(temp, file)
    return true
  } catch (error) {
    console.error(`[store] could not write ${file}: ${messageOf(error)}`)
    return false
  }
}

// Last line of defence: the window's close handler already flushes, but a quit
// path that skips it (SIGTERM, a crash in a teardown handler) still lands here.
process.once('exit', () => flush())

function quarantine(file: string, why: string): string {
  const backup = `${file}.corrupt-${Date.now()}`
  try {
    fs.renameSync(file, backup)
    return `${file} was ${why}; moved to ${backup}`
  } catch (error) {
    return `${file} was ${why} and could not be moved aside: ${messageOf(error)}`
  }
}

function messageOf(error: unknown): string {
  return error instanceof Error ? error.message : String(error)
}
